BEGIN;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_class WHERE relname = 'newsletter_subscribers') THEN
    RAISE EXCEPTION 'Newsletter relation already exists: inspect and reconcile; no changes applied';
  END IF;
  -- Preserve the existing authenticated admin subscriber-list UI using the
  -- established, protected administrator predicate. Do not redefine auth here.
  IF NOT EXISTS (
    SELECT 1 FROM pg_proc WHERE oid = to_regprocedure('public.is_blog_admin()')
      AND prosecdef AND proconfig @> ARRAY['search_path=""']::text[]
  ) OR NOT EXISTS (
    SELECT 1 FROM pg_trigger WHERE tgrelid = to_regclass('public.profiles')
      AND tgname = 'protect_profile_authority' AND tgenabled = 'O'
  ) THEN
    RAISE EXCEPTION 'Protected admin predicate prerequisite missing: stop and review; no changes applied';
  END IF;
END $$;

CREATE TABLE public.newsletter_subscribers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  name text,
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'unsubscribed')),
  source text NOT NULL DEFAULT 'website'
    CHECK (source IN ('homepage', 'blog-insights', 'newsletter-popup', 'website')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  subscribed_at timestamptz NOT NULL DEFAULT now(),
  unsubscribed_at timestamptz,
  CONSTRAINT newsletter_email_normalized CHECK (
    email = lower(btrim(email)) AND length(email) BETWEEN 3 AND 200
    AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'
  )
);

ALTER TABLE public.newsletter_subscribers ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.newsletter_subscribers FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.newsletter_subscribers_id_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.newsletter_subscribers TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.newsletter_subscribers_id_seq TO service_role;
-- No public signup/read policy: the validated server API performs subscriptions.
GRANT SELECT ON public.newsletter_subscribers TO authenticated;
CREATE POLICY newsletter_admin_read ON public.newsletter_subscribers
  FOR SELECT TO authenticated USING ((SELECT public.is_blog_admin()));

NOTIFY pgrst, 'reload schema';
COMMIT;
